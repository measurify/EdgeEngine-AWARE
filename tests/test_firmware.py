def random_mlp_model(rng: np.random.Generator, n_modes: int = 3, hidden: int = 32, output: str = "multidiscrete_logits") -> dict:
    n_out = 3 + (1 + n_modes) if output == "multidiscrete_logits" else 3 * (1 + n_modes)
    dims = [18, hidden, hidden, n_out]
    acts = ["tanh", "relu", "linear"]
    layers = []
    for i in range(3):
        W = rng.normal(0, 1 / np.sqrt(dims[i]), size=(dims[i + 1], dims[i])).astype(np.float32)
        b = rng.normal(0, 0.1, size=dims[i + 1]).astype(np.float32)
        layers.append({"W": W.tolist(), "b": b.tolist(), "activation": acts[i]})
    model = {"type": "mlp", "input_dim": 18, "layers": layers, "output": output, "n_modes": n_modes}
    if output == "multidiscrete_logits":
        model["output_split"] = [3, 1 + n_modes]
    return model


class Harness:
    """Compile the C harness for a bundle and talk to it over pipes."""

    def __init__(self, bundle: dict, build_dir: Path):
        build_dir.mkdir(parents=True, exist_ok=True)
        (build_dir / "eea_policy_data.h").write_text(export_header(bundle, source="test"))
        exe = build_dir / "eea_harness"
        cmd = [CC, "-std=c99", "-O2", "-Wall", "-Wextra", "-Werror", "-I", str(FIRMWARE), "-I", str(build_dir),
               str(FIRMWARE / "eea_node.c"), str(FIRMWARE / "test" / "eea_harness.c"), "-o", str(exe), "-lm"]
        subprocess.run(cmd, check=True, capture_output=True, text=True)
        self.proc = subprocess.Popen([str(exe)], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True, bufsize=1)

    def cmd(self, line: str) -> str:
        assert self.proc.stdin and self.proc.stdout
        self.proc.stdin.write(line + "\n")
        self.proc.stdin.flush()
        out = self.proc.stdout.readline()
        if not out:
            raise RuntimeError(f"harness died on {line!r}")
        return out.strip()

    def obs(self) -> np.ndarray:
        return np.array([float.fromhex(x) for x in self.cmd("O").split()], dtype=np.float32)

    def close(self) -> None:
        if self.proc.stdin:
            self.proc.stdin.close()
        self.proc.wait(timeout=10)


def hexfloats(values) -> str:
    return " ".join(float(v).hex() for v in np.asarray(values, dtype=np.float32).astype(float))


def random_event_stream(rng: np.random.Generator, profile: NodeProfile, n_steps: int = 300):
    """Yield (kind, payload) events resembling a real episode."""
    dt = profile.timestep_s
    now = 0.0
    events = []
    measurement = None
    for k in range(n_steps):
        tod = now % 86400.0
        cap = 300.0 if k < n_steps // 2 else 250.0
        energy = float(rng.uniform(0, cap))
        harvest = float(max(0.0, rng.normal(0.002, 0.002)))
        prio = int(rng.integers(0, 3)) if rng.random() < 0.3 else -1
        events.append(("B", (now, tod, energy, cap, harvest, prio)))
        if rng.random() < 0.6:
            level = int(rng.integers(1, 3))
            measurement = Measurement(float(rng.uniform(0, 1)), now, level, profile.sensing_noise_std[level])
            events.append(("M", measurement))
        if measurement is not None and rng.random() < 0.4:
            mode = int(rng.integers(0, profile.n_modes))
            r = rng.random()
            acked = None if r < 0.1 else bool(r < 0.7)
            margin = float(rng.normal(8, 6)) if (acked and rng.random() < 0.9) else None
            events.append(("X", (Packet(measurement, now), acked, now, mode, margin)))
        if rng.random() < 0.1:
            events.append(("Q", int(rng.integers(0, 3))))
        events.append(("O", None))
        now += dt
    return events


def drive(events, tracker: NodeStateTracker, builder: ObservationBuilder, harness: Harness, policy=None, mlp=None):
    """Replay the events on both sides; return the list of (py_obs, c_obs, py_act, c_act, py_mlp, c_mlp)."""
    rows = []
    for kind, payload in events:
        if kind == "B":
            now, tod, energy, cap, harvest, prio = payload
            tracker.begin_step(now_s=now, time_of_day_s=tod, energy_j=energy, capacity_j=cap, harvest_power_w=harvest, priority=None if prio < 0 else prio)
            assert harness.cmd(f"B {now!r} {tod!r} {energy!r} {cap!r} {harvest!r} {prio}") == "ok"
        elif kind == "M":
            m: Measurement = payload
            tracker.on_measurement(m)
            assert harness.cmd(f"M {m.value!r} {m.timestamp_s!r} {m.level} {m.noise_std!r}") == "ok"
        elif kind == "X":
            packet, acked, now, mode, margin = payload
            tracker.on_transmission(packet, acked, now, mode=mode, margin_db=margin)
            a = -1 if acked is None else int(acked)
            assert harness.cmd(f"X {packet.sent_at_s!r} {a} {now!r} {mode} {int(margin is not None)} {0.0 if margin is None else margin!r}") == "ok"
        elif kind == "Q":
            tracker.set_priority(payload)
            assert harness.cmd(f"Q {payload}") == "ok"
        elif kind == "O":
            py_obs = builder.build(tracker.state())
            c_obs = harness.obs()
            py_act = c_act = py_mlp = c_mlp = None
            if policy is not None:
                py_act = tuple(int(x) for x in policy.act(py_obs))
                c_act = tuple(int(x) for x in harness.cmd("R").split())
            if mlp is not None:
                py_mlp = (tuple(int(x) for x in mlp.act(py_obs)), mlp.forward(py_obs))
                parts = harness.cmd("N").split()
                c_mlp = ((int(parts[0]), int(parts[1])), np.array([float.fromhex(x) for x in parts[2:]], dtype=np.float32))
            rows.append((py_obs, c_obs, py_act, c_act, py_mlp, c_mlp))
    return rows


