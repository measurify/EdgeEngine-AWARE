"""Equivalence of the C runtime (firmware/) with the Python reference.

The harness ``firmware/test/eea_harness.c`` is compiled together with a header
generated by ``tools/export_c.py`` from a ``PolicyBundle``; the same event
stream (begin_step / measurement / transmission) is fed to the Python
``NodeStateTracker`` and to the C tracker, and observations, rule-based
actions, plan_execution results and MLP actions are compared.

Skipped when no C compiler is available.
"""

