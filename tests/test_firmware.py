def test_export_header_mentions_bundle(profile):
    policy = RuleBasedPolicy(RuleBasedParams(), profile)
    bundle = json.loads(export_policy(policy, profile, policy_type="rule_based", notes="unit").to_json())
    header = export_header(bundle, source="x")
    assert "EEA_HAS_RULE_PARAMS" in header and "EEA_PROFILE" in header
    assert '#define EEA_BUNDLE_NOTES "unit"' in header
    assert ".n_modes = 3," in header


def test_tracker_and_observation_match_bit_for_bit(profile, rule_harness):
    rng = np.random.default_rng(1)
    tracker = NodeStateTracker(profile)
    builder = ObservationBuilder(profile)
    assert rule_harness.cmd("Z") == "ok"
    rows = drive(random_event_stream(rng, profile, 400), tracker, builder, rule_harness)
    assert len(rows) == 400
    max_diff = 0.0
    exact = 0
    for py_obs, c_obs, *_ in rows:
        assert py_obs.dtype == np.float32 and c_obs.shape == (18,)
        diff = np.abs(py_obs.astype(np.float64) - c_obs.astype(np.float64))
        max_diff = max(max_diff, float(diff.max()))
        exact += int(np.array_equal(py_obs, c_obs))
    # sin/cos may differ by one float32 ulp between libm builds; everything else is exact
    assert max_diff <= 1.2e-7, max_diff
    assert exact >= 0.95 * len(rows)


def test_rule_based_actions_match(profile, rule_harness):
    rng = np.random.default_rng(2)
    tracker = NodeStateTracker(profile)
    builder = ObservationBuilder(profile)
    policy = RuleBasedPolicy(RuleBasedParams(), profile)
    assert rule_harness.cmd("Z") == "ok"
    rows = drive(random_event_stream(rng, profile, 600), tracker, builder, rule_harness, policy=policy)
    mismatches = [(p, c) for _, _, p, c, _, _ in rows if p != c]
    assert not mismatches, mismatches[:5]
    # the stream must exercise the rules: several distinct actions
    assert len({p for _, _, p, _, _, _ in rows}) >= 4


def test_rule_based_on_explicit_observations(profile, rule_harness):
    """Random observations (not only reachable ones) cover every branch."""
    rng = np.random.default_rng(3)
    policy = RuleBasedPolicy(RuleBasedParams(), profile)
    n_mismatch = 0
    for _ in range(2000):
        obs = rng.uniform(0, 1, 18).astype(np.float32)
        obs[11] = rng.choice([0.0, 0.5, 1.0])  # priority
        obs[6] = rng.choice([0.0, 0.2, 0.8])  # quality tag
        if rng.random() < 0.3:
            obs[14] = 1.0  # no link estimate
        if rng.random() < 0.2:
            obs[8] = 1.0  # never reported
        assert rule_harness.cmd("V " + hexfloats(obs)) == "ok"
        c_act = tuple(int(x) for x in rule_harness.cmd("R").split())
        py_act = tuple(int(x) for x in policy.act(obs))
        n_mismatch += py_act != c_act
    assert n_mismatch == 0


def test_plan_execution_matches(profile, rule_harness):
    rng = np.random.default_rng(4)
    for _ in range(500):
        sense, tx = int(rng.integers(0, 3)), int(rng.integers(0, 1 + profile.n_modes))
        cap = float(rng.choice([300.0, 120.0, 30.0]))
        stored = float(rng.uniform(0, cap))
        has_meas = bool(rng.random() < 0.5)
        plan = plan_execution(
            np.array([sense, tx]),
            stored_energy_j=stored,
            baseline_energy_j=profile.baseline_energy_j,
            reserve_energy_j=profile.reserve_soc * cap,
            sensing_energy_j=profile.sensing_energy_j,
            tx_energy_j=profile.tx_energy_j,
            has_measurement=has_meas,
        )
        parts = rule_harness.cmd(f"P {sense} {tx} {stored!r} {cap!r} {int(has_meas)}").split()
        c_level, c_tx, c_mode = int(parts[0]), bool(int(parts[1])), int(parts[2])
        c_sense_j, c_tx_j = float.fromhex(parts[3]), float.fromhex(parts[4])
        c_rej = (bool(int(parts[5])), bool(int(parts[6])), bool(int(parts[7])))
        assert (c_level, c_tx, c_mode) == (plan.sensing_level, plan.transmit, plan.mode)
        assert c_sense_j == plan.sensing_energy_j and c_tx_j == plan.tx_energy_j
        assert c_rej == ("sensing:insufficient_energy" in plan.rejected, "transmit:no_measurement" in plan.rejected, "transmit:insufficient_energy" in plan.rejected)


def test_mlp_actions_match(profile, mlp_model, mlp_harness):
    rng = np.random.default_rng(5)
    mlp = NumpyMLPPolicy(mlp_model)
    tracker = NodeStateTracker(profile)
    builder = ObservationBuilder(profile)
    assert mlp_harness.cmd("Z") == "ok"
    rows = drive(random_event_stream(rng, profile, 300), tracker, builder, mlp_harness, mlp=mlp)
    n_bad = 0
    for _, _, _, _, (py_act, py_logits), (c_act, c_logits) in rows:
        np.testing.assert_allclose(c_logits, py_logits, rtol=1e-5, atol=1e-6)
        if py_act != c_act:  # only acceptable at a numerical tie
            n1 = 3
            for seg in (py_logits[:n1], py_logits[n1:]):
                top2 = np.sort(seg)[-2:]
                assert top2[1] - top2[0] < 1e-5
            n_bad += 1
    assert n_bad <= 1
    assert len({a for _, _, _, _, (a, _), _ in rows}) >= 2


def test_mlp_flat_q_values_decoding(profile, tmp_path):
    model = random_mlp_model(np.random.default_rng(9), output="flat_q_values")
    bundle = json.loads(export_policy(NumpyMLPPolicy(model), profile, policy_type="mlp", model=model).to_json())
    h = Harness(bundle, tmp_path / "c_flat")
    try:
        mlp = NumpyMLPPolicy(model)
        rng = np.random.default_rng(10)
        for _ in range(300):
            obs = rng.uniform(0, 1, 18).astype(np.float32)
            assert h.cmd("V " + hexfloats(obs)) == "ok"
            parts = h.cmd("N").split()
            c_act = (int(parts[0]), int(parts[1]))
            py_act = tuple(int(x) for x in mlp.act(obs))
            q = mlp.forward(obs)
            if c_act != py_act:
                top2 = np.sort(q)[-2:]
                assert top2[1] - top2[0] < 1e-5
    finally:
        h.close()


def test_exported_ppo_bundle_if_present(profile, tmp_path):
    bundle_path = ROOT / "examples" / "bundles" / "ppo_default.json"
    if not bundle_path.exists():
        pytest.skip("shipped PPO bundle not found")
    bundle = json.loads(bundle_path.read_text())
    h = Harness(bundle, tmp_path / "c_ppo")
    try:
        mlp = NumpyMLPPolicy(bundle["model"])
        env = EdgeEngineAwareEnv(default_config())
        obs, _ = env.reset(seed=1234)
        n_bad = 0
        for _ in range(400):
            assert h.cmd("V " + hexfloats(obs)) == "ok"
            parts = h.cmd("N").split()
            c_act = (int(parts[0]), int(parts[1]))
            py_act = tuple(int(x) for x in mlp.act(obs))
            if c_act != py_act:
                n_bad += 1
            obs, _, term, trunc, _ = env.step(np.array(py_act))
            if term or trunc:
                break
        assert n_bad == 0
    finally:
        h.close()
